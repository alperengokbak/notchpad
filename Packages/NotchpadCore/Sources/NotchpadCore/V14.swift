import Foundation

// MARK: Update check

/// Asks GitHub for the latest release, at most once a day (and when he clicks "Check for updates…").
public enum UpdateCheck {
    public static let latestReleaseAPI = URL(string: "https://api.github.com/repos/alperengokbak/notchpad/releases/latest")!
    public static let interval: TimeInterval = 24 * 3600

    /// "v1.10.0" > "1.9.2". Anything that isn't a version is never newer.
    public static func isNewer(_ candidate: String, than current: String) -> Bool {
        guard let a = parts(candidate), let b = parts(current) else { return false }
        for i in 0..<max(a.count, b.count) {
            let x = i < a.count ? a[i] : 0, y = i < b.count ? b[i] : 0
            if x != y { return x > y }
        }
        return false
    }

    private static func parts(_ s: String) -> [Int]? {
        let trimmed = s.hasPrefix("v") ? String(s.dropFirst()) : s
        let numbers = trimmed.split(separator: ".").map { Int($0) }
        guard !numbers.isEmpty, !numbers.contains(nil) else { return nil }
        return numbers.compactMap { $0 }
    }

    /// The release's version (without "v") and its page, from GitHub's JSON.
    public static func parseLatest(_ data: Data) -> (version: String, url: URL)? {
        guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let tag = json["tag_name"] as? String, let page = json["html_url"] as? String,
              let url = URL(string: page) else { return nil }
        return (tag.hasPrefix("v") ? String(tag.dropFirst()) : tag, url)
    }

    /// The "Update available" item only ever opens Notchpad's own release pages on github.com,
    /// whatever the API reply says.
    public static func isTrustedReleasePage(_ url: URL) -> Bool {
        url.scheme == "https" && url.host == "github.com" && url.path.hasPrefix("/alperengokbak/notchpad/releases")
    }

    public static func isDue(lastCheck: Date?, now: Date) -> Bool {
        guard let lastCheck else { return true }
        return now.timeIntervalSince(lastCheck) >= interval
    }
}

// MARK: Clipboard history

/// One thing he copied: text (links are text too) or a picture.
public struct ClipEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var text: String?
    /// PNG/TIFF data of a copied picture. Never saved to disk.
    public var imageData: Data?
    public var date: Date

    enum CodingKeys: String, CodingKey { case id, text, date }

    public init(id: UUID = UUID(), text: String? = nil, imageData: Data? = nil, date: Date) {
        self.id = id; self.text = text; self.imageData = imageData; self.date = date
    }
}

/// The last 30 copies, newest first. Copying the same text again moves it to the top.
public struct ClipboardHistory: Equatable, Sendable {
    public static let limit = 30
    public private(set) var entries: [ClipEntry] = []

    public init(entries: [ClipEntry] = []) {
        self.entries = Array(entries.prefix(Self.limit))
    }

    public mutating func add(text: String, now: Date) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        entries.removeAll { $0.text == text }
        entries.insert(ClipEntry(text: text, date: now), at: 0)
        trim()
    }

    public mutating func add(imageData: Data, now: Date) {
        entries.removeAll { $0.imageData == imageData }
        entries.insert(ClipEntry(imageData: imageData, date: now), at: 0)
        trim()
    }

    public mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
    public mutating func clear() { entries.removeAll() }

    /// What goes to disk: text only.
    public var forSaving: [ClipEntry] { entries.filter { $0.text != nil } }

    /// Copies a password manager marks as secret (or as temporary / made by an app) are never kept.
    /// These markers are the shared convention from nspasteboard.org; 1Password also adds its own type.
    public static func shouldSkip(types: [String]) -> Bool {
        types.contains { t in
            t == "org.nspasteboard.ConcealedType" || t == "org.nspasteboard.TransientType"
                || t == "org.nspasteboard.AutoGeneratedType" || t.hasPrefix("com.agilebits")
        }
    }

    /// Password managers, as a second line of defence (most also mark their copies as secret).
    public static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.apple.Passwords", "com.apple.keychainaccess",
    ]

    /// Also skips anything copied while a password manager is the app in front.
    public static func shouldSkip(types: [String], frontApp: String?) -> Bool {
        shouldSkip(types: types) || frontApp.map(passwordManagers.contains) == true
    }

    private mutating func trim() {
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
    }
}

// MARK: Recent files

public enum RecentFiles {
    /// Ordinary documents only: no apps, folders, hidden files or anything inside ~/Library.
    public static func keep(path: String, isFolder: Bool, isApp: Bool, home: String) -> Bool {
        guard !isFolder, !isApp else { return false }
        if path.hasPrefix(home + "/Library/") { return false }
        return !path.split(separator: "/").contains { $0.hasPrefix(".") }
    }

    /// "Just now", "5 min ago", "2 h ago", "Yesterday", "3 days ago".
    public static func ago(_ date: Date, now: Date) -> String {
        let s = max(0, now.timeIntervalSince(date))
        switch s {
        case ..<60: return "Just now"
        case ..<3600: return "\(Int(s / 60)) min ago"
        case ..<86400: return "\(Int(s / 3600)) h ago"
        case ..<(2 * 86400): return "Yesterday"
        default: return "\(Int(s / 86400)) days ago"
        }
    }
}

// MARK: Progress bar on play/pause

extension NowPlaying {
    /// Apple Music's notification has no position, so a pause or resume would show 0:00 for a moment.
    /// For the same song, keep where it had got to; a new song, or a notification with a position, wins.
    public func carryingPosition(from old: NowPlaying?, now: Date) -> NowPlaying {
        guard let old, old.title == title, old.artist == artist, position == 0 else { return self }
        var copy = self
        copy.position = old.position(at: now)
        copy.positionDate = now
        return copy
    }
}
